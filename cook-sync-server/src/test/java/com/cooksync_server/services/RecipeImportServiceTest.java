    @Test
    void processImport_resolvesUnknownUnitCode_toPieceFallback_andCreatesPrivateRecipe() throws Exception {
        RecipeImportJob job = RecipeImportJob.builder().id("job-1").user(user)
                .sourceType(RecipeImportJob.SourceType.WEB).sourceUrl("https://example.com/recipe")
                .status(RecipeImportJob.Status.PENDING).build();
        when(recipeImportJobRepository.findWithUserById("job-1")).thenReturn(Optional.of(job));
        when(unitRepository.findAll()).thenReturn(List.of(pieceUnit, gramUnit));
        when(robotsTxtChecker.isAllowed(anyString())).thenReturn(true);
        when(webPageTextExtractor.fetchReadableContent(anyString()))
                .thenReturn(new WebPageTextExtractor.PageContent("recipe text", "https://example.com/cover.jpg"));

        ExtractedRecipe extracted = new ExtractedRecipe(
                "Test Recipe", "A description.", "EASY", 10, 20, 4,
                List.of(
                        new ExtractedRecipe.ExtractedIngredient("flour", new java.math.BigDecimal("200"), "g"),
                        new ExtractedRecipe.ExtractedIngredient("eggs", new java.math.BigDecimal("2"), "not-a-real-unit")),
                List.of("Mix.", "Bake."));
        when(extractionProvider.extractFromWebPage(anyString(), any())).thenReturn(Optional.of(extracted));
        when(unitRepository.findByCodeIgnoreCase("g")).thenReturn(Optional.of(gramUnit));
        when(unitRepository.findByCodeIgnoreCase("not-a-real-unit")).thenReturn(Optional.empty());
        when(unitRepository.findByCodeIgnoreCase("piece")).thenReturn(Optional.of(pieceUnit));

        RecipeResponse created = new RecipeResponse("recipe-1", null, "Test Recipe", "EASY", "PRIVATE",
                10, 20, 4, 0, null, List.of(), "2026-01-01T00:00:00", null, List.of(), java.util.Set.of(),
                List.of(), null, List.of(), false, null, null);
        when(recipeService.createRecipe(any(RecipeCreateRequestDTO.class), eq("chef@example.com"))).thenReturn(created);

        service.processImport("job-1");

        verify(recipeService).createRecipe(createRequestCaptor.capture(), eq("chef@example.com"));
        RecipeCreateRequestDTO createRequest = createRequestCaptor.getValue();
        assertEquals("PRIVATE", createRequest.visibility());
        assertEquals(2, createRequest.ingredients().size());
        assertEquals("unit-gram", createRequest.ingredients().get(0).unitId());
        assertEquals("unit-piece", createRequest.ingredients().get(1).unitId());

        verify(recipeService).setSourceAttribution(eq("recipe-1"), eq("https://example.com/recipe"), anyString());
        verify(recipeImportJobRepository, times(2)).save(jobCaptor.capture());
        assertEquals(RecipeImportJob.Status.SUCCEEDED, jobCaptor.getValue().getStatus());
        assertEquals("recipe-1", jobCaptor.getValue().getResultRecipeId());
    }

