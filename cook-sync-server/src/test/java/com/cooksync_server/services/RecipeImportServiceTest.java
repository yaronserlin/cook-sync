    @BeforeEach
    void setUp() throws Exception {
        user = new User();
        user.setId("user-1");
        user.setEmail("chef@example.com");

        pieceUnit = Unit.builder().id("unit-piece").code("piece").name("Piece").namePlural("Pieces").build();
        gramUnit = Unit.builder().id("unit-gram").code("g").name("Gram").namePlural("Grams").build();

        // Executor and imageDownloadClient are both final fields the service builds/initializes
        // itself, not constructor-settable via @InjectMocks alone since RecipeImportServiceImp's
        // constructor is generated by Lombok in declared field order - reflection keeps this
        // test independent of that ordering.
        java.lang.reflect.Field executorField = RecipeImportServiceImp.class.getDeclaredField("notificationExecutor");
        executorField.setAccessible(true);
        executorField.set(service, synchronousExecutor);

        java.lang.reflect.Field imageClientField = RecipeImportServiceImp.class.getDeclaredField("imageDownloadClient");
        imageClientField.setAccessible(true);
        imageClientField.set(service, imageDownloadClient);
        // lenient: only the PHOTO-path tests actually exercise this download call; every WEB
        // test would otherwise trip strict-stubbing's "unnecessary stubbing" check.
        org.mockito.Mockito.lenient().when(imageDownloadClient.get().uri(anyString()).retrieve().body(byte[].class))
                .thenReturn(new byte[]{1, 2, 3});
    }

