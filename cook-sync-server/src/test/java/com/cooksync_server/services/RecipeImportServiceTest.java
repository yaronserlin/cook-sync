    @Test
    void processImport_photoImport_multiplePhotos_passesAllImages_toExtractionProvider_andAttributesFirstPhoto() throws Exception {
        RecipeImportJob job = jobWithPhotos(List.of(
                "https://cdn.example.com/p1.jpg", "https://cdn.example.com/p2.jpg", "https://cdn.example.com/p3.jpg"));
        when(recipeImportJobRepository.findWithUserById("job-1")).thenReturn(Optional.of(job));
        when(unitRepository.findAll()).thenReturn(List.of(pieceUnit));

        ExtractedRecipe extracted = new ExtractedRecipe(
                "Handwritten Soup", "", "EASY", 5, 30, 6, List.of(), List.of("Simmer."));
        when(extractionProvider.extractFromImages(any(), any())).thenReturn(Optional.of(extracted));

        RecipeResponse created = new RecipeResponse("recipe-2", null, "Handwritten Soup", "EASY", "PRIVATE",
                5, 30, 6, 0, null, List.of(), "2026-01-01T00:00:00", null, List.of(), java.util.Set.of(),
                List.of(), null, List.of(), false, null, null);
        when(recipeService.createRecipe(any(RecipeCreateRequestDTO.class), eq("chef@example.com"))).thenReturn(created);

        @SuppressWarnings("unchecked")
        ArgumentCaptor<List<ImageInput>> imagesCaptor = ArgumentCaptor.forClass(List.class);

        service.processImport("job-1");

        verify(extractionProvider).extractFromImages(imagesCaptor.capture(), any());
        assertEquals(3, imagesCaptor.getValue().size());

        verify(recipeService).createRecipe(createRequestCaptor.capture(), eq("chef@example.com"));
        assertEquals("https://cdn.example.com/p1.jpg", createRequestCaptor.getValue().primaryImageUrl());
        verify(recipeService).setSourceAttribution(eq("recipe-2"), eq("https://cdn.example.com/p1.jpg"), eq("Imported from photos"));
    }

    /**
     * Builds a PHOTO {@link RecipeImportJob} with the given source photo URLs already attached in
     * order, matching how {@link RecipeImportServiceImp#startImport} assembles one.
     */
    private RecipeImportJob jobWithPhotos(List<String> photoUrls) {
        RecipeImportJob job = RecipeImportJob.builder().id("job-1").user(user)
                .sourceType(RecipeImportJob.SourceType.PHOTO)
                .status(RecipeImportJob.Status.PENDING).build();
        for (int i = 0; i < photoUrls.size(); i++) {
            job.getSourceImages().add(RecipeImportJobImage.builder()
                    .job(job).imageUrl(photoUrls.get(i)).sortOrder(i).build());
        }
        return job;
    }

    private static String findUnitCodeById(RecipeCreateRequestDTO request, String unitId) {
        return request.ingredients().stream()
                .filter(i -> i.unitId().equals(unitId))
                .findFirst()
                .map(i -> unitId.equals("unit-gram") ? "g" : "piece")
                .orElse(null);
    }
